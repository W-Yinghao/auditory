    p0 = dict(m0.named_parameters()); name = {id(p): n for n, p in model.named_parameters()}
    for L, g in zip(led["groups"], pg):
        num = den = 0.0
        for p in g["params"]:
            q = p0[name[id(p)]].to(p.device)
            num += float(((p - q) ** 2).sum()); den += float((q ** 2).sum())
        L["rel_weight_change"] = math.sqrt(num) / (math.sqrt(den) + 1e-12); L["abs_weight_change"] = math.sqrt(num)
    _ledger_save(led)
    return {k: v for k, v in led.items() if k != "_path"}


