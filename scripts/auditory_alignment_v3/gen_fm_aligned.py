def aligned_windows(E, e0, t, pre, post):
    """E [C, N] cohort EEG; e0 [n] segment starts; t [n, Q] query offsets (samples) -> [n*Q, C, pre+post] windows
    [t - pre, t + post) with zeros before the segment start (relative index < 0)."""
    n, L = len(e0), pre + post
    rel = t.reshape(n, -1)[:, :, None] - pre + torch.arange(L, device=E.device)[None, None]  # [n, Q, L]
    idx = (e0.reshape(n, 1, 1) + rel).clamp(min=0)
    W = E[:, idx.reshape(-1)].reshape(E.shape[0], n, rel.shape[1], L).permute(1, 2, 0, 3).float()  # [n, Q, C, L]
    W = W * (rel >= 0)[:, :, None, :].to(W.dtype)
    return W.reshape(-1, E.shape[0], L)


class AlignedBatcher(DenseBatcher):
    def __init__(self, coh, spec, row, dev, grid):
        super().__init__(coh, spec, row, dev, grid)
        self.pre, self.post = int(round(PRE_S * self.fs)), int(round(POST_S * self.fs))

    def windows(self, e0, t):
        return aligned_windows(self.E, e0, t, self.pre, self.post)


class AlignedPatchLinear(nn.Module):
    def __init__(self, C, E, d):
        super().__init__()
        self.norm = nn.LayerNorm(E); self.lin = nn.Linear(C * E, d)

    def forward(self, h):  # h [n, C, E] -> [n, d]
        return F.normalize(self.lin(self.norm(h).flatten(1)), dim=-1)


class AlignedFM(nn.Module):
    def __init__(self, bb, d):
        super().__init__()
        self.bb = bb; self.readout = AlignedPatchLinear(len(bb.channel_names), bb.E, d)

    def forward(self, W):  # W [n, C, pre+post] native -> [n, d]
        h = self.bb(W)
        assert h.shape[2] == 1, h.shape  # exactly one backbone patch per query
        return self.readout(h[:, :, 0])


