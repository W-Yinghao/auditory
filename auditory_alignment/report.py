def f(b, d=4):
    if not b or b.get("est") is None:
        return "–"
    s = f"{b['est']:+.{d}f}"
    if "ci_low" in b:
        s += f" [{b['ci_low']:+.{d}f}, {b['ci_high']:+.{d}f}]"
    return s


def fp(b, d=3):
    if not b or b.get("est") is None:
        return "–"
    return f"{b['est']:.{d}f}" + (f" [{b['ci_low']:.{d}f}, {b['ci_high']:.{d}f}]" if "ci_low" in b else "")


def key(block, ds, obj, tgt, win, var="default"):
    return "|".join((block, ds, obj, tgt, win, var))


def cov(full, k):
    c = full.get(k)
    return f"{c['n_units']}/{c['n_units_planned']}" if c else "0"


def g(full, k, grp, m):
    c = full.get(k)
    return c["groups"].get(grp, {}).get(m) if c else None


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(map(str, r)) + " |" for r in rows]
    return "\n".join(out)


def targets_of(full, ds):
    return sorted({k.split("|")[3] for k in full if k.split("|")[1] == ds and k.startswith("core|")})


