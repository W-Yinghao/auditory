    axs[0].legend(fontsize=7); fig.tight_layout(); fig.savefig(os.path.join(FIG, "learning_curves.png"), dpi=130); plt.close(fig)
    # 3. groups
    fig, axs = plt.subplots(1, 4, figsize=(16, 3.4))
    for ax, ds in zip(axs, DSN):
        m = "unified/gain_bits" if ds != "private_bdf" else "head_gain_vs_base_bits"
        gs = sorted({gg for o in OBJ for gg in ((full.get(key("core", ds, o, MAIN_T[ds], "full")) or {}).get("groups", {}))} - {"all"})
        for j, o in enumerate(OBJ):
            for i, gg in enumerate(gs):
                b = g(full, key("core", ds, o, MAIN_T[ds], "full"), gg, m)
                if b and b.get("est") is not None:
                    x = i + (j - 1.5) * 0.18
                    ax.bar(x, b["est"], 0.17, color=cols[o], label=o if i == 0 else None)
                    if "ci_low" in b:
                        ax.plot([x, x], [b["ci_low"], b["ci_high"]], "k-", lw=0.8)
        ax.axhline(0, color="k", lw=0.5); ax.set_xticks(range(len(gs))); ax.set_xticklabels(gs); ax.set_title(f"{DSN[ds]} full ({m})", fontsize=9)
