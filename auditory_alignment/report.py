    cols = {"NCE": "#4C72B0", "FMCA": "#55A868", "CS_SINGLE": "#C44E52", "CS_MULTI": "#8172B2"}
    # 1. core gain by window
    fig, axs = plt.subplots(1, 4, figsize=(16, 3.6))
    for ax, ds in zip(axs, DSN):
        m = "unified/gain_bits" if ds != "private_bdf" else "head_gain_vs_base_bits"
