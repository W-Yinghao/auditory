def write_ext(path, n=7):
    """A synthetic plan_ext.jsonl of n rows of other families -> its guard (lines, sha256 prefix)."""
    rows = [{"dataset": "dtu", "subject_fold": i % 5, "content_fold": 0, "seed": 3401, "seed_scope": "breadth",
             "experiment_id": f"ALN3X_{0xabc000 + i:016x}", "family_id": "ALN32_RESIDUAL", "job_kind": "train", "spec": {"objective": "NCE"},
             "registered": "synthetic", "logical_dependencies": [f"ALN3_{i % 3:016x}"], "status": "registered_extension"} for i in range(n)]
    with open(path, "w") as f:
        f.write("".join(json.dumps(r) + "\n" for r in rows))
    return guard_of(path)


def guard_of(path):
    with open(path, "rb") as f:
        raw = f.read()
    return len(raw.decode().splitlines()), hashlib.sha256(raw).hexdigest()[:16]


def ext_rows(path):
    with open(path) as f:
        return [json.loads(line) for line in f]


def call(M, tmp, argv, ext=None, guard=None, **kw):
    """M.main on temporary paths only (never the live defaults)."""
    ext = ext or os.path.join(tmp, "plan_ext.jsonl")
    kw.setdefault("out", os.path.join(tmp, "out"))
    kw.setdefault("record", os.path.join(tmp, "no_record.md"))
    kw.setdefault("plan_rows", _base_rows())
    for p in (ext, kw["out"], kw["record"]):
        assert os.path.realpath(p).startswith(os.path.realpath(str(tmp))), p
    return M.main(argv, plan_ext=ext, guard=guard or guard_of(ext), **kw)


def margs(fx, *extra):
    return ["--manifest", fx["manifest_path"], "--manifest-sha", fx["manifest_sha256"], *extra]


