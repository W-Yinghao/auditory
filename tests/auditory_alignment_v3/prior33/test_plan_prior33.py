def _expect_refusal(root, kind, needle):
    target = os.path.join(root, RP.TARGET[kind])
    before = _sha_file(target)
    rc, log = run_recipe(kind, root)
    assert rc != 0 and needle in log, log
    assert _sha_file(target) == before                    # never replaced
    return log


