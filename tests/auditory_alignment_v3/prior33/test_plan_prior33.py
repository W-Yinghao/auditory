def _patch_text(kind):
    with open(os.path.join(PATCHES, f"{kind}.prior33.patch"), encoding="utf-8") as f:
        return f.read()


def _apply_to_copy(kind, tmp):
    """A temporary copy of the live file with the patch applied by GNU patch -> its path (sha256 checked on both sides)."""
    text = _patch_text(kind)
    live, want = RP.header_field(text, "live-sha256"), RP.header_field(text, "patched-sha256")
    src = os.path.join(REPO, RP.TARGET[kind])
    dst = os.path.join(tmp, os.path.basename(src))
    shutil.copy2(src, dst)
    got = hashlib.sha256(open(dst, "rb").read()).hexdigest()
    assert got == live, (f"{RP.TARGET[kind]} changed since {kind}.prior33.patch was generated (live {got[:16]}, header {live[:16]}): "
                         f"regenerate with python -B -m auditory_alignment_v3.prior33.registry_patch write-patches")
    r = subprocess.run(["patch", "--no-backup-if-mismatch", "--silent", dst], input=text, capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr
    assert hashlib.sha256(open(dst, "rb").read()).hexdigest() == want
    assert not os.path.exists(dst + ".orig") and not os.path.exists(dst + ".rej")
    return dst


