def test_record_comparison_fails_closed(tmp_path):
    """record_problems on a small registry: a missing or empty units directory, a code group or family without records (unless
    named with allow), an unknown allow name, a latest record per group and per (family, group) pair with another hash, the
    policy group of a family, and the prior33 groups compared only once they have records."""
    reg = SimpleNamespace(FAMILY_CODE={"g1": [], "g2": [], "gp": [], "prior33_donor": []}, POLICY_GROUP={"FD": "gp"},
                          FAMILY_GROUP={"F1": "g1", "F2": "g1", "F3": "g2", "FD": "g2", P + "DONOR": "prior33_donor"})
    H = {"g1": "a" * 16, "g2": "b" * 16, "gp": "c" * 16, "prior33_donor": "d" * 16}
    units = str(tmp_path / "units")

    def check(allow=()):
        return RP.record_problems(RP.latest_records(units), H, reg, allow)
    probs, _, info = check()
    assert len(probs) == 1 and "does not exist" in probs[0] and info["code_groups_compared"] == 0
    os.makedirs(units)
    probs, _, info = check(allow=["g1", "g2", "gp", "F1", "F2", "F3", "FD"])          # an empty directory: no escape
    assert len(probs) == 1 and "holds no unit record" in probs[0] and info["code_groups_required"] == 3 and info["families_required"] == 4
    now = time.time()
    for i, (fam, g) in enumerate((("F1", "g1"), ("F2", "g1"), ("F3", "g2"), ("FD", "gp"))):
        write_unit(units, f"ALN3X_{i:016x}", g, H[g], now - 50, fam)
    probs, notes, info = check()
    assert probs == [] and (info["code_groups_compared"], info["families_compared"], info["family_group_pairs_compared"]) == (3, 4, 4)
    write_unit(units, "ALN3X_" + "9" * 16, "g1", "e" * 16, now - 90, "F2")            # F2's other record: older, another hash
    assert check()[0] == []                                                            # not F2's latest
    os.utime(os.path.join(units, "ALN3X_0000000000000001.json"), (now - 95, now - 95))   # now it is F2's latest (not g1's)
    probs = check()[0]
    assert probs == [f"family F2 (code group g1): its latest unit record ALN3X_{'9' * 16}.json has code_hash {'e' * 16}, the patched "
                     f"registry gives {'a' * 16}"]
    os.remove(os.path.join(units, "ALN3X_" + "9" * 16 + ".json"))
    os.remove(os.path.join(units, "ALN3X_0000000000000001.json"))                      # F2 never ran
    probs, notes, _ = check()
    assert len(probs) == 1 and probs[0].startswith("family F2 has no unit record") and "--allow-unrecorded F2" in probs[0]
    probs, notes, _ = check(allow=["F2"])
    assert probs == [] and any(n.startswith("family F2 has no unit record (allowed") for n in notes)
    assert check(allow=["F2", "nope"])[0] == ["--allow-unrecorded ['nope']: not an existing code group or family of the registry"]
    os.remove(os.path.join(units, "ALN3X_0000000000000003.json"))                      # gp (FD's policy group) and FD: no record
    probs = check(allow=["F2"])[0]
    assert sorted(p.split(" has no")[0] for p in probs) == ["code group gp", "family FD"]
    write_unit(units, "ALN3X_" + "8" * 16, "gp", H["gp"], now, "FD")
    write_unit(units, "ALN3X_" + "7" * 16, "prior33_donor", "0" * 16, now, P + "DONOR")  # a prior33 record: compared once it exists
    probs = check(allow=["F2"])[0]
    assert len(probs) == 2 and all("prior33_donor" in p and "0" * 16 in p for p in probs)


