def test_closure_eager_lazy_and_relative_imports(tmp_path):
    root = str(tmp_path)
    files = {
        "auditory_alignment_v3/__init__.py": "",
        "auditory_alignment_v3/core.py": "from .registry import X  # noqa: F401\n",
        "auditory_alignment_v3/registry.py": "X = 1\n",
        "auditory_alignment_v3/aln3_reference/__init__.py": '"""doc"""\n__version__ = "1"\n',
        "auditory_alignment_v3/aln3_reference/calibration.py": "",
        "auditory_alignment_v3/prior33/__init__.py": "",
        "auditory_alignment_v3/prior33/run_donor.py": "import auditory_alignment_v3.prior33.a\nfrom .. import core\nfrom ..aln3_reference "
                                                      "import calibration\n\n\nclass K:\n    from . import b  # class body: eager\n\n\n"
                                                      "def f():\n    from .c import thing  # lazy\n",
        "auditory_alignment_v3/prior33/a.py": "from auditory_alignment import data  # noqa: F401\nfrom auditory_alignment_v2 import other\n",
        "auditory_alignment_v3/prior33/b.py": "",
        "auditory_alignment_v3/prior33/c.py": "from . import d  # eager inside c, lazy from the runner\n",
        "auditory_alignment_v3/prior33/d.py": "",
        "auditory_alignment/__init__.py": "", "auditory_alignment/data.py": "",
        "auditory_alignment_v2/__init__.py": "", "auditory_alignment_v2/other.py": "",
    }
    for rel, text in files.items():
        os.makedirs(os.path.dirname(os.path.join(root, rel)), exist_ok=True)
        with open(os.path.join(root, rel), "w") as f:
            f.write(text)
    reached, unresolved = RP.closure("auditory_alignment_v3.prior33.run_donor", root)
    eager = {r for r, (e, _) in reached.items() if e}
    lazy = {r for r, (e, _) in reached.items() if not e}
    assert {"auditory_alignment_v3/prior33/a.py", "auditory_alignment_v3/prior33/b.py", "auditory_alignment_v3/core.py",
            "auditory_alignment_v3/registry.py", "auditory_alignment_v3/aln3_reference/calibration.py",
            "auditory_alignment/data.py", "auditory_alignment_v2/other.py"} <= eager
    assert lazy == {"auditory_alignment_v3/prior33/c.py", "auditory_alignment_v3/prior33/d.py"} and unresolved == []
    code = {"prior33_donor": [("auditory_alignment_v3", "core.py"), ("auditory_alignment_v3/prior33", "run_donor.py"),
                              ("auditory_alignment_v3/prior33", "a.py"), ("auditory_alignment_v3/aln3_reference", "calibration.py")]}
    probs, notes = RP.closure_problems(code, [("auditory_alignment", "data.py")], root)
    assert len(probs) == 1 and "prior33_donor: auditory_alignment_v3/prior33/b.py is imported at module level" in probs[0]
    assert any("prior33/c.py is reachable only through an import inside a function" in n for n in notes)
    assert any("ALN2 module auditory_alignment_v2/other.py" in n for n in notes)
    assert not any("registry.py" in p or "__init__" in p for p in probs)
    assert RP.inert_init(os.path.join(root, "auditory_alignment_v3/aln3_reference/__init__.py"))


