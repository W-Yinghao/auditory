def test_append_rows_reports_other_writers(M, tmp_path, monkeypatch):
    """append_rows against a lane that ignores the lock: a change after the guarded read (refused, nothing replaced), an
    in-place append to the old file during the rename, and a replace from an older read after it (both reported)."""
    p = os.path.join(tmp_path, "plan_ext.jsonl")
    new = [{"experiment_id": "ALN3X_" + "1" * 16, "family_id": P + "DONOR", "spec": {}}]
    write_ext(p)
    raw = open(p, "rb").read()
    with open(p, "ab") as f:
        f.write(b'{"experiment_id": "other lane"}\n')
    changed = open(p, "rb").read()
    with pytest.raises(M.PlanError, match="changed while the block was built"):
        M.append_rows(p, raw, new)
    assert open(p, "rb").read() == changed and not [f for f in os.listdir(tmp_path) if "prior33" in f]
    real_replace = os.replace

    def replace_with_inplace_append(src, dst):
        if dst == p:
            with open(p, "ab") as f:
                f.write(INPLACE)
        return real_replace(src, dst)
    write_ext(p)
    raw = open(p, "rb").read()
    monkeypatch.setattr(M.os, "replace", replace_with_inplace_append)
    with pytest.raises(M.PlanError, match=f"old file changed size by {len(INPLACE)} bytes during the rename"):
        M.append_rows(p, raw, new)
    monkeypatch.setattr(M.os, "replace", real_replace)
    assert open(p, "rb").read() == raw + (json.dumps(new[0]) + "\n").encode()

    def replace_from_older_read(seconds):
        with open(p + ".other", "wb") as f:
            f.write(raw + b'{"experiment_id": "late lane"}\n')
        real_replace(p + ".other", p)
    write_ext(p)
    raw = open(p, "rb").read()
    monkeypatch.setattr(M.time, "sleep", replace_from_older_read)
    with pytest.raises(M.PlanError, match="no longer begins with the written bytes"):
        M.append_rows(p, raw, new)
    monkeypatch.undo()
    baks = sorted(f for f in os.listdir(tmp_path) if ".before_prior33_" in f)
    assert len(baks) == 2 and not [f for f in os.listdir(tmp_path) if "tmp_prior33" in f]      # one backup per append, none lost


